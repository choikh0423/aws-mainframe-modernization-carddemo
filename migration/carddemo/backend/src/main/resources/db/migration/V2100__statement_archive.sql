-- S-21 OnlineStatements (band V2100-V2199).
--
-- Durable archive of rendered statements: one row per card per cycle, written
-- by CREASTMT and served online. Not a legacy dataset; the flat TEXT_FILE /
-- HTML_FILE outputs of CREASTMT are unchanged.
--
-- Stream-private: only com.carddemo.statements reads or writes it.
-- Portable between H2 and PostgreSQL.

CREATE TABLE statement_archive (
    stmt_id             BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    acct_id             NUMERIC(11)   NOT NULL,
    card_num            VARCHAR(16)   NOT NULL,
    cycle               CHAR(7)       NOT NULL,
    generated_ts        TIMESTAMP     NOT NULL,
    txn_count           INTEGER       NOT NULL,
    total_amount        NUMERIC(11,2) NOT NULL,
    text_body           TEXT          NOT NULL,
    html_body           TEXT          NOT NULL,
    CONSTRAINT pk_statement_archive PRIMARY KEY (stmt_id),
    CONSTRAINT uk_statement_archive_card_cycle UNIQUE (card_num, cycle)
);

CREATE INDEX idx_statement_archive_acct_cycle ON statement_archive (acct_id, cycle DESC);
